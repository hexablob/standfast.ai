import type { Dirent } from "node:fs";
import {
  mkdir,
  readdir,
  readFile,
  rm,
  rmdir,
  stat,
  writeFile,
} from "node:fs/promises";
import { dirname, join, relative, resolve, sep } from "node:path";
import { type Ctx, pageAll, unwrap } from "./commands.js";
import { out } from "./output.js";

/**
 * `standfast export` — the anti-lock-in guarantee, whole.
 *
 * `docs/11-git-export.md` is the contract and this file is its implementation:
 * every document byte-for-byte at the customer's own path, every atom projected
 * into Markdown under a reserved `.standfast/`, a manifest that carries the
 * content hashes, and owned-directory semantics so a deletion on the server is
 * a deletion in the tree. Exporting twice against an unchanged knowledge base
 * produces a byte-identical tree — which is why no tracked file carries a
 * timestamp. The export time goes to `--json`, where a script can have it.
 */

/** The shape of an atom as the list route serves it, structurally. */
export type ExportAtom = {
  id: string;
  documentId: string;
  sectionId: string;
  statement: string;
  kind: string;
  status: string;
  sourceQuote: string;
  sourceSpan: { start: number; end: number };
  ratifiedAt: string | null;
  supersededBy: string | null;
  ratifiedByKind?: "human" | "agent" | null;
  ratifiedByName?: string | null;
};

type ExportSection = {
  id: string;
  ordinal: number;
  headingPath: string[];
  sectionHash: string;
};

type Manifest = {
  standfast: string;
  server: string;
  projects: {
    slug: string;
    id: string;
    atoms: number;
    documents: { path: string; id: string; content_hash: string }[];
  }[];
};

const README = `# Standfast export

A full export of the knowledge base. Nothing in it needs Standfast to read: it
is Markdown and one JSON file.

- \`<slug>/\` — one directory per project. Documents sit at their own paths,
  byte-for-byte, so \`diff -r\` against the folder they came from shows exactly
  what changed.
- \`<slug>/.standfast/atoms/<path>\` — the atoms projected from the document at
  \`<path>\`, one file per document, with the decisions humans took about them.
- \`standfast.json\` — the manifest. \`sha256sum\` of any exported document
  reproduces its \`content_hash\` there, so the export verifies with tools that
  ship with an operating system.

This directory is owned by \`standfast export\`: re-exporting removes whatever
the server no longer has. Keep it in version control if you want the history.
`;

/**
 * The ordering inside a projection file: section order first, active atoms
 * before superseded ones, then span start, then id as the final tiebreak. The
 * API returns atoms newest-first, which is right for a listing and wrong for a
 * record — a re-export after any write would reorder every file. Exported for
 * the test that pins this.
 */
export function compareAtoms(
  ordinalOf: (sectionId: string) => number,
): (a: ExportAtom, b: ExportAtom) => number {
  const superseded = (atom: ExportAtom) =>
    atom.status === "superseded" ? 1 : 0;
  return (a, b) =>
    ordinalOf(a.sectionId) - ordinalOf(b.sectionId) ||
    superseded(a) - superseded(b) ||
    a.sourceSpan.start - b.sourceSpan.start ||
    (a.id < b.id ? -1 : a.id > b.id ? 1 : 0);
}

/**
 * One document's atom projection, in the byte-exact shape
 * `docs/11-git-export.md` fixes: front matter, the heading path joined with
 * `›` for display (identity stays with the hash), `section <ordinal> ·
 * <hash8>…`, the atom id's first eight hex digits as the heading, the bold
 * statement, the field bullets, and the source quote as a blockquote. The span
 * counts Unicode code points and its dash is an en dash — both matter to an
 * offline verifier.
 */
export function projection(
  slug: string,
  doc: { path: string; id: string },
  sections: ExportSection[],
  atoms: ExportAtom[],
): string {
  const byId = new Map(sections.map((s) => [s.id, s]));
  const sorted = [...atoms].sort(
    compareAtoms((id) => byId.get(id)?.ordinal ?? Number.MAX_SAFE_INTEGER),
  );

  const lines: string[] = [
    "---",
    "standfast: atoms/v1",
    `project: ${slug}`,
    `document: ${doc.path}`,
    `document_id: ${doc.id}`,
    "---",
    "",
    `# Atoms projected from ${doc.path}`,
    "",
    "Generated by `standfast export`. Every statement below is a projection of the",
    "quoted text in the document at the same path. Do not edit this file. Edit the",
    "document.",
  ];

  let current: string | null = null;
  for (const atom of sorted) {
    if (atom.sectionId !== current) {
      current = atom.sectionId;
      const section = byId.get(atom.sectionId);
      if (!section) {
        throw new Error(
          `Atom ${atom.id} names a section the server did not list for ${doc.path}.`,
        );
      }
      const heading =
        section.headingPath.length > 0
          ? section.headingPath.join(" › ")
          : "(no heading)";
      lines.push(
        "",
        `## ${heading}`,
        "",
        `section ${section.ordinal} · ${section.sectionHash.slice(0, 8)}…`,
      );
    }

    const bullets = [`- kind: ${atom.kind}`, `- status: ${atom.status}`];
    if (atom.ratifiedAt !== null) {
      const kind = atom.ratifiedByKind ? ` (${atom.ratifiedByKind})` : "";
      bullets.push(
        `- ratified: ${atom.ratifiedAt.slice(0, 10)} by ${atom.ratifiedByName ?? "unknown"}${kind}`,
      );
    }
    if (atom.supersededBy !== null) {
      // The successor by its own short id, the same form the headings use.
      bullets.push(`- superseded_by: ${atom.supersededBy.slice(0, 8)}`);
    }
    bullets.push(`- span: ${atom.sourceSpan.start}–${atom.sourceSpan.end}`);

    lines.push(
      "",
      `### ${atom.id.slice(0, 8)}`,
      "",
      `**${atom.statement}**`,
      "",
      ...bullets,
      "",
      ...atom.sourceQuote
        .split("\n")
        .map((line) => (line === "" ? ">" : `> ${line}`)),
    );
  }

  return `${lines.join("\n")}\n`;
}

/**
 * Joins a server-supplied path under a base directory, refusing anything that
 * escapes it.
 *
 * `doc.path` comes from the API. Writing it to disk unchecked would let
 * `../../.ssh/authorized_keys` out of a compromised or merely buggy server —
 * a server should not be able to choose where a client writes.
 */
export function safeJoin(base: string, candidate: string): string {
  const baseResolved = resolve(base);
  const joined = resolve(baseResolved, candidate);
  const rel = relative(baseResolved, joined);
  if (rel === "" || rel.startsWith("..") || rel.startsWith(sep)) {
    throw new Error(
      `Refusing to write outside the export directory: ${candidate}`,
    );
  }
  return joined;
}

/**
 * Where a document lands inside its project directory. `.standfast/` is
 * reserved for the atom projection, so a document stored under it is refused
 * with an error naming it — a collision that fails loudly is a bug report, and
 * one that fails quietly is data loss.
 */
export function exportDestination(base: string, docPath: string): string {
  if (docPath.split("/")[0] === ".standfast") {
    throw new Error(
      `Refusing to export ${docPath}: .standfast/ is reserved for the atom projection.`,
    );
  }
  return safeJoin(base, docPath);
}

/**
 * The sentinel on the destructive half of export. A directory that does not
 * exist or is empty is ours to create. One that holds a parseable
 * `standfast.json` is a previous export, and its manifest says which project
 * directories we own. Anything else is somebody's directory, and
 * `standfast export ~` must not be a way to delete a home directory.
 */
export async function readOwnedManifest(
  target: string,
): Promise<Manifest | null> {
  let entries: string[];
  try {
    entries = await readdir(target);
  } catch {
    return null;
  }
  if (entries.length === 0) {
    return null;
  }
  try {
    const parsed: unknown = JSON.parse(
      await readFile(join(target, "standfast.json"), "utf8"),
    );
    if (
      parsed !== null &&
      typeof parsed === "object" &&
      "standfast" in parsed
    ) {
      return parsed as Manifest;
    }
  } catch {
    // Unreadable or unparseable: fall through to the refusal.
  }
  throw new Error(
    `${target} exists and is not a previous export (no parseable standfast.json). ` +
      "Export owns its directory — it removes what it did not write — so it refuses one it cannot prove it wrote. Point it at a new or empty directory.",
  );
}

/**
 * Deletion is part of export. Everything under a project directory that this
 * run did not write goes, and so does a project directory the previous
 * manifest lists but this fetch did not return — otherwise the tree lies by
 * omission and every later `git diff` misses the most important change.
 */
async function sweepStale(
  target: string,
  written: Set<string>,
  currentSlugs: Set<string>,
  previous: Manifest | null,
): Promise<string[]> {
  const swept: string[] = [];
  const relPath = (p: string) => relative(target, p).split(sep).join("/");

  for (const slug of currentSlugs) {
    let entries: Dirent[];
    try {
      entries = await readdir(join(target, slug), {
        recursive: true,
        withFileTypes: true,
      });
    } catch {
      continue;
    }
    const directories: string[] = [];
    for (const entry of entries) {
      const full = join(entry.parentPath, entry.name);
      if (entry.isDirectory()) {
        directories.push(full);
      } else if (!written.has(full)) {
        await rm(full, { force: true });
        swept.push(relPath(full));
      }
    }
    // Deepest first, so a directory emptied above becomes removable itself.
    directories.sort((a, b) => b.length - a.length);
    for (const directory of directories) {
      try {
        await rmdir(directory);
      } catch {
        // Not empty: it still holds something written this run.
      }
    }
  }

  for (const project of previous?.projects ?? []) {
    const slug = project?.slug;
    if (typeof slug !== "string" || slug === "" || currentSlugs.has(slug)) {
      continue;
    }
    // The slug came from a manifest on disk; it still does not get to escape.
    const directory = safeJoin(target, slug);
    try {
      await stat(directory);
    } catch {
      continue;
    }
    await rm(directory, { recursive: true, force: true });
    swept.push(`${relPath(directory)}/`);
  }

  return swept;
}

/**
 * Full Markdown export to a directory the customer controls.
 *
 * `docs/02-principles.md` (11): anti-lock-in is a feature. It removes a
 * purchase objection for very little engineering, and it is only credible if
 * it exists before anyone asks.
 *
 * The order of operations is deliberate: fetch everything, build the whole
 * tree in memory, write the files, write the manifest last — so the ownership
 * record never names a tree that was not fully written — and only then sweep.
 */
export async function exportAll(ctx: Ctx): Promise<void> {
  const target = resolve(ctx.args[0] ?? "standfast-export");
  const previous = await readOwnedManifest(target);
  const client = ctx.client();

  const projects = (
    await pageAll(async (query) =>
      unwrap(await client.GET("/v1/projects", { params: { query } })),
    )
  ).sort((a, b) => (a.slug < b.slug ? -1 : a.slug > b.slug ? 1 : 0));

  // Everything below re-sorts what the API returned newest-first: projects by
  // slug, documents by path, atoms inside `projection`. Determinism is the
  // contract — a byte-identical tree on an unchanged knowledge base.
  const files = new Map<string, string>();
  const manifest: Manifest = {
    standfast: "export/v1",
    server: ctx.config.baseUrl ?? "",
    projects: [],
  };
  let documents = 0;

  for (const project of projects) {
    const base = join(target, project.slug);
    const docs = (
      await pageAll(async (query) =>
        unwrap(
          await client.GET("/v1/projects/{projectId}/documents", {
            params: { path: { projectId: project.id }, query },
          }),
        ),
      )
    ).sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
    const atoms = await pageAll(async (query) =>
      unwrap(
        await client.GET("/v1/projects/{projectId}/atoms", {
          params: { path: { projectId: project.id }, query },
        }),
      ),
    );
    const byDocument = new Map<string, ExportAtom[]>();
    for (const atom of atoms) {
      byDocument.set(atom.documentId, [
        ...(byDocument.get(atom.documentId) ?? []),
        atom,
      ]);
    }

    const manifestDocuments: Manifest["projects"][number]["documents"] = [];
    for (const doc of docs) {
      files.set(exportDestination(base, doc.path), doc.body);
      documents += 1;
      manifestDocuments.push({
        path: doc.path,
        id: doc.id,
        content_hash: doc.contentHash,
      });

      const docAtoms = byDocument.get(doc.id) ?? [];
      if (docAtoms.length > 0) {
        const sections = await pageAll(async (query) =>
          unwrap(
            await client.GET("/v1/documents/{documentId}/sections", {
              params: { path: { documentId: doc.id }, query },
            }),
          ),
        );
        files.set(
          safeJoin(base, `.standfast/atoms/${doc.path}`),
          projection(project.slug, doc, sections, docAtoms),
        );
      }
    }

    manifest.projects.push({
      slug: project.slug,
      id: project.id,
      atoms: atoms.length,
      documents: manifestDocuments,
    });
  }

  files.set(join(target, "README.md"), README);

  const written = new Set<string>();
  for (const [destination, content] of files) {
    await mkdir(dirname(destination), { recursive: true });
    // Verbatim, with no newline appended and no line-ending normalisation:
    // `sha256sum` on the exported file must reproduce `content_hash`.
    await writeFile(destination, content, "utf8");
    written.add(destination);
  }

  const manifestPath = join(target, "standfast.json");
  await writeFile(
    manifestPath,
    `${JSON.stringify(manifest, null, 2)}\n`,
    "utf8",
  );
  written.add(manifestPath);

  const swept = await sweepStale(
    target,
    written,
    new Set(projects.map((p) => p.slug)),
    previous,
  );

  // The run report may carry a timestamp; a tracked file may not.
  out(
    ctx.format,
    `Exported ${documents} document(s) to ${target}` +
      (swept.length > 0 ? `\nSwept ${swept.length} stale path(s).` : ""),
    { target, written: documents, swept, exportedAt: new Date().toISOString() },
  );
}
